#!/usr/bin/env python3
"""Decide which files a push to main must sign, and refuse a bad policy release.

Prints (and writes to --github-output as `files=`) the space-separated tracked
files that match --globs and differ between --before and --after; with --all,
every tracked file that matches.

For every changed policy with "status": "active" it requires a published_at
that is a UTC timestamp, not in the future, and strictly later than the
published_at of the version it replaces (a replaced template or a first copy
has none to compare with). It notes, without failing, a policy that does not
yet declare trust.policy_distribution "sigstore-rekor".

Clients order policies by the transparency log's own time, not by published_at,
so these rules are hygiene for readers and monitors, not the rollback defence.

Standard library only.
"""
from __future__ import annotations

import argparse
import datetime as dt
import fnmatch
import json
import re
import subprocess
import sys

SAFE_PATH = re.compile(r"[A-Za-z0-9][A-Za-z0-9._/-]*\Z")
STAMP = re.compile(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(\.\d{3})?Z\Z")


def git(*args: str, check: bool = True) -> str:
    result = subprocess.run(["git", *args], capture_output=True, text=True)
    if check and result.returncode != 0:
        raise SystemExit(f"git {' '.join(args[:2])} failed: {result.stderr.strip()[:300]}")
    return result.stdout


def show(commit: str, path: str) -> bytes | None:
    result = subprocess.run(["git", "show", f"{commit}:{path}"], capture_output=True)
    return result.stdout if result.returncode == 0 else None


def parse_stamp(text: object) -> dt.datetime | None:
    if not isinstance(text, str) or not STAMP.match(text):
        return None
    return dt.datetime.fromisoformat(text.replace("Z", "+00:00"))


def check_policy(path: str, new: bytes, old: bytes | None, now: dt.datetime) -> list[str]:
    try:
        policy = json.loads(new)
    except ValueError:
        return [f"{path}: not valid JSON"]
    if not isinstance(policy, dict) or policy.get("status") != "active":
        return []
    problems = []
    trust = policy.get("trust") if isinstance(policy.get("trust"), dict) else {}
    if trust.get("policy_distribution") != "sigstore-rekor" or trust.get("detached_policy_signature") is not True:
        # Not an error: the first signed policy is the one that was already
        # being served, byte for byte, and it predates signing. Policies
        # generated by update_policy_signed.py declare the signed distribution.
        print(f'::notice::{path} still declares the pre-signing distribution (trust.policy_distribution "https-origin"); it is signed as it is')
    published = parse_stamp(policy.get("published_at"))
    if published is None:
        problems.append(f"{path}: published_at must look like 2026-11-24T12:00:00.000Z")
    elif published > now + dt.timedelta(minutes=5):
        problems.append(f"{path}: published_at is in the future")
    if old is not None and published is not None:
        try:
            previous = parse_stamp(json.loads(old).get("published_at"))
        except (ValueError, AttributeError):
            previous = None
        if previous is not None and published <= previous:
            problems.append(f"{path}: published_at {policy['published_at']} is not later than the version it replaces")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--before", required=True, help="commit before the push (all zeros for a new branch)")
    parser.add_argument("--after", required=True)
    parser.add_argument("--globs", required=True, help="space-separated path patterns that are signed")
    parser.add_argument("--all", action="store_true", help="sign every file in scope, changed or not (the first run, when nothing has been signed yet)")
    parser.add_argument("--github-output")
    args = parser.parse_args(argv)

    patterns = args.globs.split()
    before = args.before if args.before and set(args.before) != {"0"} and git("cat-file", "-t", args.before, check=False).strip() == "commit" else None
    tracked = [line for line in git("ls-tree", "-r", "--name-only", args.after).splitlines() if any(fnmatch.fnmatchcase(line, pattern) for pattern in patterns)]
    changed, problems = [], []
    now = dt.datetime.now(dt.timezone.utc)
    for path in tracked:
        new = show(args.after, path)
        old = show(before, path) if before else None
        if new is None or (new == old and not args.all):
            continue
        if not SAFE_PATH.match(path) or ".." in path.split("/"):
            problems.append(f"{path}: file name is not safe to sign")
            continue
        changed.append(path)
        if fnmatch.fnmatchcase(path, "policies/*.json"):
            # An unchanged file (signed only because of --all) replaces nothing.
            problems.extend(check_policy(path, new, None if new == old else old, now))
    for problem in problems:
        print(f"::error::{problem}")
    if problems:
        return 1
    print(" ".join(changed))
    if args.github_output:
        with open(args.github_output, "a") as stream:
            stream.write(f"files={' '.join(changed)}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
